@app.get("/posts")
def get_posts():

    con = get_connection()

    try:
        cursor = con.cursor()

        cursor.execute("""
            SELECT *
            FROM posts
            ORDER BY id DESC
        """)

        rows = cursor.fetchall()

        return [post_to_dict(row) for row in rows]

    finally:
        con.close()


