
from fastapi import FastAPI, HTTPException
from google import genai
from dotenv import load_dotenv
import sqlite3
import os
import json
from datetime import datetime

app = FastAPI(title="Content Saathi API")

# ==================================================
# PATHS AND ENVIRONMENT
# ==================================================

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

ENV_PATH = os.path.join(BASE_DIR, ".env")
DB_PATH = os.path.join(BASE_DIR, "database", "content_saathi.db")
SHOP_PATH = os.path.join(BASE_DIR, "data", "shop.json")

load_dotenv(ENV_PATH)

# ==================================================
# GEMINI CONFIGURATION
# ==================================================

api_key = os.getenv("GEMINI_API_KEY")

if not api_key:
    raise RuntimeError(
        "GEMINI_API_KEY missing. Check D:\\content-saathi\\.env"
    )

client = genai.Client(api_key=api_key)

MODEL = "gemini-3.8-flash"


# ==================================================
# DATABASE CONNECTION
# ==================================================

def get_connection():
    if not os.path.exists(DB_PATH):
        raise RuntimeError(f"Database not found: {DB_PATH}")

    return sqlite3.connect(DB_PATH)


# ==================================================
# LOAD SHOP DATA
# ==================================================

def load_shop():
    try:
        with open(SHOP_PATH, "r", encoding="utf-8") as file:
            return json.load(file)
    except FileNotFoundError:
        raise RuntimeError(f"Shop configuration not found: {SHOP_PATH}")
    except json.JSONDecodeError:
        raise RuntimeError("Invalid JSON in data/shop.json")


# ==================================================
# GENERATE AI CONTENT USING GEMINI
# ==================================================

def generate_content():

    shop = load_shop()

    today = datetime.now()
    date_key = today.strftime("%d-%m-%Y")
    day = today.strftime("%A")

    festival = shop.get("calendar", {}).get(
        date_key,
        "No major festival today"
    )

    prompt = f"""
You are Content Saathi, an AI social media content writer.

Create ONE short, attractive and copy-paste-ready daily promotional post
for a local shop.

Shop Name: {shop["shop_name"]}
Business Type: {shop["business_type"]}
Location: {shop["location"]}
Products: {", ".join(shop["products"])}
Tone: {shop["tone"]}
Language: {shop["language"]}

Today's Date: {date_key}
Today's Day: {day}
Today's Festival: {festival}

Rules:
- Write in natural Hindi-English.
- Keep it short and punchy.
- Make it suitable for Telegram, Instagram and Google Business.
- Mention the shop naturally.
- Do not invent discounts, prices or offers.
- Do not say that the post was generated by AI.
- Include 1 or 2 suitable emojis.
- Add one simple local hashtag.
- Return ONLY the post text.
"""

    try:
        response = client.models.generate_content(
            model=MODEL,
            contents=prompt,
            config={
                "temperature": 0.7
            }
        )

        content = (response.text or "").strip()

        if not content:
            raise RuntimeError("Gemini returned an empty response.")

    except Exception as exc:
        raise RuntimeError(f"Gemini content generation failed: {exc}") from exc

    return {
        "date": date_key,
        "day": day,
        "festival": festival,
        "content": content
    }


# ==================================================
# HELPER: CONVERT DATABASE ROW TO DICTIONARY
# ==================================================

def post_to_dict(row):
    return {
        "id": row[0],
        "shop_name": row[1],
        "generated_date": row[2],
        "day": row[3],
        "festival": row[4],
        "content": row[5],
        "status": row[6],
        "created_at": row[7]
    }


