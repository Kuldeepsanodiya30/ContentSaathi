# ==================================================
# REGENERATE POST
# ==================================================

@app.post("/regenerate/{post_id}")
def regenerate_post(post_id: int):

    con = get_connection()

    try:
        cursor = con.cursor()

        cursor.execute("""
            SELECT *
            FROM posts
            WHERE id = ?
              AND status = 'DRAFT'
        """, (post_id,))

        old_post = cursor.fetchone()

        if not old_post:
            raise HTTPException(
                status_code=404,
                detail="Draft not found or already processed"
            )

        # Reject the old draft
        cursor.execute("""
            UPDATE posts
            SET status = 'REJECTED'
            WHERE id = ?
              AND status = 'DRAFT'
        """, (post_id,))

        con.commit()

    finally:
        con.close()

    # Create a replacement draft.
    # The previous draft is rejected and remains in history.
    return generate_post()
