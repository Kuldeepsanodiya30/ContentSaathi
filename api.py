# APPROVE POST
# ==================================================

@app.put("/approve/{post_id}")
def approve_post(post_id: int):

    con = get_connection()

    try:
        cursor = con.cursor()

        cursor.execute("""
            UPDATE posts
            SET status = 'APPROVED'
            WHERE id = ?
              AND status = 'DRAFT'
        """, (post_id,))

        affected = cursor.rowcount
        con.commit()

        if affected == 0:
            raise HTTPException(
                status_code=404,
                detail="Post not found or already processed"
            )

        return {
            "message": "Post approved successfully",
            "post_id": post_id,
            "status": "APPROVED"
        }

    finally:
        con.close()


