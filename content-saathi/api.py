# ==================================================

@app.put("/approve/{post_id}")
def approve_post(post_id: int):

    con = get_connection()
    cursor = con.cursor()

    cursor.execute("""
        UPDATE posts
        SET status = 'APPROVED'
        WHERE id = ?
        AND status = 'DRAFT'
    """, (post_id,))

    affected = cursor.rowcount

    con.commit()
    con.close()

    if affected == 0:

        return {
            "message": "Post not found or already processed",
            "post_id": post_id
        }

    return {
        "message": "Post Approved Successfully!",
        "post_id": post_id,
        "status": "APPROVED"
    }


