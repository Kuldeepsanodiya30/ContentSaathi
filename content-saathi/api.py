@app.post("/regenerate/{post_id}")
def regenerate_post(post_id: int):

    con = get_connection()
    cursor = con.cursor()

    # ------------------------------------------------
    # FIND CURRENT DRAFT
    # ------------------------------------------------

    cursor.execute("""
        SELECT *
        FROM posts
        WHERE id = ?
        AND status = 'DRAFT'
    """, (post_id,))

    old_post = cursor.fetchone()

    if not old_post:

        con.close()

        return {
            "message": "Draft not found or already processed",
            "post_id": post_id
        }

    # ------------------------------------------------
    # REJECT OLD DRAFT
    # ------------------------------------------------

    cursor.execute("""
        UPDATE posts
        SET status = 'REJECTED'
        WHERE id = ?
    """, (post_id,))

    con.commit()
    con.close()

    # ------------------------------------------------
    # CREATE NEW DRAFT
    # ------------------------------------------------

    return generate_post()