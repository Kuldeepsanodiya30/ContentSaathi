@app.get("/posts")
def get_posts():

    con = get_connection()
    cursor = con.cursor()

    cursor.execute("""
        SELECT *
        FROM posts
        ORDER BY id DESC
    """)

    rows = cursor.fetchall()

    con.close()

    posts = []

    for row in rows:

        posts.append({
            "id": row[0],
            "shop_name": row[1],
            "generated_date": row[2],
            "day": row[3],
            "festival": row[4],
            "content": row[5],
            "status": row[6],
            "created_at": row[7]
        })

    return posts


