# ==================================================
# GENERATE POST
# ==================================================

@app.post("/generate")
def generate_post():

    today = datetime.now()

    date_key = today.strftime("%d-%m-%Y")

    con = get_connection()
    cursor = con.cursor()

    # ------------------------------------------------
    # CHECK IF TODAY'S DRAFT ALREADY EXISTS
    # ------------------------------------------------

    cursor.execute("""
        SELECT *
        FROM posts
        WHERE generated_date = ?
        AND status = 'DRAFT'
        ORDER BY id DESC
        LIMIT 1
    """, (date_key,))

    existing = cursor.fetchone()

    # ------------------------------------------------
    # RETURN EXISTING DRAFT
    # ------------------------------------------------

    if existing:

        con.close()

        return {
            "message": "Today's draft already exists",
            "post_id": existing[0],
            "status": existing[6],
            "date": existing[2],
            "day": existing[3],
            "festival": existing[4],
            "content": existing[5]
        }

    # ------------------------------------------------
    # GENERATE NEW POST
    # ------------------------------------------------

    data = generate_content()

    shop = load_shop()

    cursor.execute("""
        INSERT INTO posts
        (
            shop_name,
            generated_date,
            day,
            festival,
            content,
            status
        )
        VALUES (?, ?, ?, ?, ?, ?)
    """, (
        shop["shop_name"],
        data["date"],
        data["day"],
        data["festival"],
        data["content"],
        "DRAFT"
    ))

    post_id = cursor.lastrowid

    con.commit()
    con.close()

    return {
        "message": "Today's post generated successfully",
        "post_id": post_id,
        "status": "DRAFT",
        "date": data["date"],
        "day": data["day"],
        "festival": data["festival"],
        "content": data["content"]
    }


